@section('scripts')
<script>
    document.addEventListener('DOMContentLoaded', function() {
    // Auto-generate slug from page title
    document.getElementById('page_title').addEventListener('input', function() {
        const slugField = document.getElementById('slug');
        if (!slugField.value || slugField.dataset.autoGenerated) {
            const slug = this.value.toLowerCase()
                .replace(/[^a-z0-9\s-]/g, '')
                .replace(/\s+/g, '-')
                .replace(/-+/g, '-')
                .replace(/^-+|-+$/g, '');
            slugField.value = slug;
            slugField.dataset.autoGenerated = 'true';
        }
    });

    // Mark slug as manually edited
    document.getElementById('slug').addEventListener('input', function() {
        this.dataset.autoGenerated = 'false';
    });

    // Client-side validation for page title special characters
    const pageForm = document.getElementById('pageForm');
    if (pageForm) {
        pageForm.addEventListener('submit', function(e) {
            const pageTitle = document.getElementById('page_title');
            const errorEl = document.getElementById('page_title_error');
            const val = (pageTitle.value || '').trim();
            // Allow letters (unicode), numbers, spaces and common punctuation: - & ( ) : / ' " , .
            const regex = /^[\p{L}0-9\s\-\&\(\)\:\/\'\"\,\.]+$/u;
            if (!regex.test(val)) {
                e.preventDefault();
                errorEl.textContent = 'Page title contains invalid characters. Only letters, numbers, spaces and - & ( ) : / \" , . are allowed.';
                errorEl.classList.remove('hidden');
                pageTitle.focus();
                return false;
            } else {
                if (!errorEl.classList.contains('hidden')) {
                    errorEl.classList.add('hidden');
                    errorEl.textContent = '';
                }
            }
        });
    }
});
</script>
@endsection
