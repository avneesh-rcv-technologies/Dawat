#!/usr/bin/env python3
"""Generate versioned WebP renditions of active marketing assets; retain originals.

Run from any directory with Python 3 and Pillow installed. Generated assets and
their manifest are committed, so production builds need neither Python nor Pillow.
No catalog files are deleted or overwritten.
"""
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / 'public'
OUTPUT = PUBLIC / 'website/optimized'

HEROES = [
    'website/73964bf77c75b2eba31ec165f554afb485d18dad.jpg',
    'website/images/e4c902957ed634404076ae416d26b967b43bc0f4.jpg',
    'website/images/about/enjoying-street-food-fest 1.png',
    'website/images/enjoying-street-food-fest 1.png',
    'website/images/enjoying-street-food-fest 1 (1).png',
    'website/images/enjoying-street-food-fest1.png',
]
ART = [
    'website/9fb055111b8ba926a7cb6eef104950b4819e61ce.png',
    'website/images/4647d78a91cd2c0c1d9eda99c2429ba4d36e4e7f.png',
    'website/images/about/plate-complete.png',
    'website/images/about/girl.png',
    'website/images/Blog-details/Rectangle 161125084.png',
    'website/images/young-people-enjoying-street-food 1.png',
    'website/images/9b78d4783ee0deb27fedc85b8cdedf832ebd87ae.jpg',
    'website/two-vibrant-red-pepper-slices-revealing-seeds-and-a-fleshy-interior-against-white-photo 2.png',
]


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    recipes = {}
    for path in HEROES:
        recipes[path] = ([480, 960, 1600, 2400], 86, False)
    for path in ART:
        recipes[path] = ([480, 960, 1440], 90, False)
    for name in ['spice-palace', 'curry-house', 'royal-feast', 'taj-flavors', 'masala-kitchen', 'spice-symphony', 'flavor-garden']:
        recipes[f'website/images/restaurants/{name}-comp.jpg'] = ([320, 640, 960], 86, False)
    for path in (PUBLIC / 'website/images/Frames').glob('*.png'):
        recipes[str(path.relative_to(PUBLIC))] = ([80, 160, 240], 90, False)
    for path in (PUBLIC / 'website/images').glob('OBJECTS*.png'):
        recipes[str(path.relative_to(PUBLIC))] = ([320, 640], 90, True)
    for path in ['website/images/dawat-wordmark.png', 'website/images/Blog-details/Ellipse 58.png', 'dawat.png']:
        recipes[path] = ([160, 320, 640, 824] if 'wordmark' in path or path == 'dawat.png' else [80], 100, True)

    manifest = {}
    for source, (widths, quality, lossless) in sorted(recipes.items()):
        path = PUBLIC / source
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        with Image.open(path) as original:
            profile = original.info.get('icc_profile', b'')
            image = ImageOps.exif_transpose(original).convert('RGBA' if 'A' in original.getbands() or 'transparency' in original.info else 'RGB')
            variants = []
            for width in sorted({min(width, image.width) for width in widths}):
                height = max(1, round(image.height * width / image.width))
                # Recipe changes also change the URL: long-lived caching stays safe.
                version = 'v2-icc' if profile else 'v1'
                key = hashlib.sha256(f'{digest}:{width}:{quality}:{lossless}:{version}'.encode()).hexdigest()[:20]
                target = OUTPUT / f'{key}-{width}.webp'
                if not target.exists():
                    resized = image.resize((width, height), getattr(Image, 'Resampling', Image).LANCZOS)
                    resized.save(target, 'WEBP', quality=quality, lossless=lossless, method=6, icc_profile=profile)
                variants.append({'path': str(target.relative_to(PUBLIC)), 'width': width, 'height': height, 'bytes': target.stat().st_size})
            manifest[source] = {'width': image.width, 'height': image.height, 'sourceBytes': path.stat().st_size, 'sourceSha256': digest, 'variants': variants}
    temporary = OUTPUT / 'manifest.json.tmp'
    temporary.write_text(json.dumps(manifest, indent=2) + '\n')
    temporary.replace(OUTPUT / 'manifest.json')
    unique = {v['path']: v['bytes'] for item in manifest.values() for v in item['variants']}
    print(f'{len(manifest)} sources; {len(unique)} unique renditions; {sum(unique.values()):,} generated bytes. Originals retained.')


if __name__ == '__main__':
    main()
